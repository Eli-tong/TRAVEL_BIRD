export const dictionary = { "zh-CN": zh, en };
export function translate(language: Language, key: TranslationKey, values: Record<string, string | number> = {}) {
  const localized = dictionary[language][key];
  const template = localized ?? dictionary["zh-CN"][key];
  if (localized === undefined && import.meta.env.DEV) {
    console.warn(`[i18n] Missing "${language}" translation for "${key}"; falling back to zh-CN.`);
  }
  return template.replace(/\{\{(\w+)\}\}/g, (match, name: string) => String(values[name] ?? match));
}

