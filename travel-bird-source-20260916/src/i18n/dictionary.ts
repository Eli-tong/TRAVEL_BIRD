export function translateError(language: Language, value: string) {
  const directKey = value in dictionary["zh-CN"] ? value as TranslationKey : legacyErrorKeys[value];
  if (directKey) return translate(language, directKey);
  const unknownFood = value.match(/^无法识别食物 ID：(.+)；原存档已保留$/);
  if (language === "en" && unknownFood) return `Unknown food ID: ${unknownFood[1]}. The original save has been preserved.`;
  return value || translate(language, "error.actionFailed");
}
